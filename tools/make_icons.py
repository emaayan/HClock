SIZES = [18, 20, 24]
CELL = 32


def main():
    names = list(ICONS)
    w, h = CELL * len(names), CELL * len(SIZES)
    svgs = []
    for row, size in enumerate(SIZES):
        for col, name in enumerate(names):
            svgs.append(
                f'<svg style="position:absolute;left:{col * CELL}px;top:{row * CELL}px" width="{size}" height="{size}" '
                f'viewBox="0 0 24 24" fill="none" stroke="#fff" stroke-width="1.8" stroke-linecap="round" '
                f'stroke-linejoin="round">{ICONS[name]}</svg>')
    html = f'<html><body style="margin:0;background:#000;width:{w}px;height:{h}px">{"".join(svgs)}</body></html>'
    tmp = tempfile.mkdtemp()
    page, shot, raw = (os.path.join(tmp, n) for n in ("icons.html", "icons.png", "icons.gray"))
    open(page, "w").write(html)
    subprocess.run([EDGE, "--headless", "--disable-gpu", "--force-device-scale-factor=1", "--hide-scrollbars",
                    f"--window-size={w},{h}", f"--screenshot={shot}", "file:///" + page.replace("\\", "/")],
                   capture_output=True, timeout=60)
    subprocess.run([FFMPEG, "-loglevel", "error", "-y", "-i", shot, "-pix_fmt", "gray", "-f", "rawvideo", raw], check=True)
    pix = open(raw, "rb").read()

    lines = ["// Generated by tools/make_icons.py. Do not edit.", "#pragma once", "#include <Arduino.h>", "",
             "struct TftIcon { uint8_t w, h; const uint8_t *alpha; };", ""]
    for row, size in enumerate(SIZES):
        for col, name in enumerate(names):
            data = bytearray()
            for y in range(size):
                start = (row * CELL + y) * w + col * CELL
                data += pix[start:start + size]
            lines.append(f"const uint8_t icon_{name}_{size}_a[] PROGMEM = {{{','.join(map(str, data))}}};")
            lines.append(f"const TftIcon icon_{name}_{size} = {{{size}, {size}, icon_{name}_{size}_a}};")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(f"{len(names)} icons x {len(SIZES)} sizes -> {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
