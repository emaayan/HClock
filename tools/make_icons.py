OUT = os.path.join(HERE, "..", "src", "native", "TftIcons.h")
EDGE = r"C:\Program Files (x86)\Microsoft\Edge\Application\msedge.exe"
FFMPEG = os.path.expandvars(r"%LOCALAPPDATA%\ffmpegio\ffmpeg-downloader\ffmpeg\bin\ffmpeg.exe")

